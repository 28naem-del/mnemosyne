#!/bin/bash
# Runs after orchestrate-resume.sh prints ORCHESTRATE_DONE (i.e. once the slow conversation 9 is
# benched or has failed in phase 1): fresh re-derivation, gzip + SHA-256 of raw parts, Zep cleanup of
# every user this run created, secret grep. Writes FINAL-10CONV.md. $0: searches/deletes only.
set -uo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"; cd "$ROOT"
OUT=out/locomo; R=FINAL-10CONV.md
until grep -q ORCHESTRATE_DONE logs/orchestrate-resume.log; do sleep 120; done
{
  echo "# Zep matched run — final 10-conversation pass ($(date -u +%FT%TZ))"; echo
  echo '## Orchestrator tail'; echo '```'; tail -25 logs/orchestrate-resume.log; echo '```'; echo
  echo '## Tables (generated by scripts/gen-report.mjs from the merged raw reports)'; echo
  cat "$OUT/tables.md"; echo
  echo '## Independent re-derivation from the raw part JSONs (scripts/rederive.mjs)'; echo
  node scripts/rederive.mjs "$OUT" "$OUT/summary.json"; echo "rederive exit $?"; echo
  echo '## Compressed raw outputs'; echo; echo '| File | bytes | SHA-256 |'; echo '|---|---:|---|'
  for f in "$OUT"/locomo-k*-part*.json "$OUT"/locomo-k5.json "$OUT"/locomo-k10.json "$OUT"/locomo-k20.json; do
    [ -f "$f" ] || continue; gzip -9 -f "$f"
    echo "| \`$f.gz\` | $(stat -f %z "$f.gz") | \`$(shasum -a 256 "$f.gz" | cut -d' ' -f1)\` |"
  done; echo
  echo '## Zep cleanup (all mnemo-zeprun-20261029-* users)'; echo '```'
  scripts/withkey.sh node scripts/cleanup.mjs 2>&1 | grep -v '^would'; echo "cleanup exit $?"
  scripts/withkey.sh node scripts/users.mjs 2>&1 | sed -E 's/(users [0-9]+).*/\1 (ids omitted)/'; echo '```'; echo
  echo '## Secret grep (counts only)'; echo '```'
  scripts/withkey.sh node scripts/secret-grep.mjs "$ROOT"; echo "secret-grep exit $?"; echo '```'
} > "$R" 2>&1
echo FINISH_DONE >> logs/finish-10conv.log
