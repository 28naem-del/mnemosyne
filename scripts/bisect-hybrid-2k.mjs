#!/usr/bin/env node
// The seeded 2,000-record bisect case on the hybrid path, written as a report.
//
//   npm run build && node scripts/bisect-hybrid-2k.mjs [--out-dir reports]
//
// Runs `runHybridBisectCase` (src/evaluation/bisect-hybrid.ts) once per dense
// index bisect supports (exact, sqlite-vec) and writes
// <out-dir>/bisect-hybrid-2k.json and <out-dir>/bisect-hybrid-2k.md. Offline and
// $0: the embedder is a deterministic hashed bag of words, the reranker is off,
// no model is loaded and nothing touches the network. Every field except the
// timings is deterministic; tests/local-bisect-hybrid-2k.test.ts re-runs the
// case and fails if the committed report no longer matches the code.
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { arch, cpus, platform } from 'node:os';
import { join, resolve } from 'node:path';
import { parseArgs } from 'node:util';
import { BISECT_HYBRID_RECORDS, BISECT_HYBRID_SEED, runHybridBisectCase } from '../dist/evaluation/bisect-hybrid.js';

const { values } = parseArgs({ options: { 'out-dir': { type: 'string' } } });
const outDir = resolve(values['out-dir'] ?? 'reports');
const git = (...args) => { try { return execFileSync('git', args, { encoding: 'utf8' }).trim(); } catch { return null; } };
const commit = git('rev-parse', 'HEAD');
// Uncommitted changes to the code the case runs mean `commit` is only the base it was measured on.
const dirty = commit === null ? null : git('status', '--porcelain', '--', 'src', 'scripts', 'package.json') !== '';

const cases = ['exact', 'sqlite-vec'].map((indexMode) => runHybridBisectCase({ indexMode }));
const report = {
  report: 'bisect-hybrid-2k',
  description: 'Seeded 2,000-record bisect case on the hybrid retrieval path: one false record displaces the verified answer at k = 1; bisect must blame exactly that record, confirmed by Oracle B re-executing the hybrid retriever.',
  seed: BISECT_HYBRID_SEED,
  records: BISECT_HYBRID_RECORDS,
  measuredAt: new Date().toISOString(),
  commit,
  dirty,
  host: { node: process.version, platform: platform(), arch: arch(), cpu: cpus()[0]?.model ?? null },
  limits: 'Synthetic corpus. The embedder is a deterministic hashed bag of words, not a semantic model, and the reranker is off: the case pins bisect on the hybrid path (fusion, dense index, stored vectors carried into each rebuild), not the quality of any model. Times vary by machine; the test bar is 60 s. An hnsw index is not supported by bisect.',
  cases,
};
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'bisect-hybrid-2k.json'), `${JSON.stringify(report, null, 2)}\n`);

const fixed = (value, digits) => (value === null || value === undefined ? 'n/a' : value.toFixed(digits));
const rows = cases.map((entry) => `| ${entry.indexRequested} | ${entry.records} | ${entry.outcome} (${entry.reason}) | ${entry.blame} | ${fixed(entry.precision, 2)} | ${entry.exactConfirmed} | ${entry.exactRetrieval} | ${entry.reembeddedPassages} | ${fixed(entry.bisectSeconds, 2)} | ${fixed(entry.totalSeconds, 2)} |`);
const markdown = `# Bisect on the hybrid path: seeded 2,000-record case

Generated by \`node scripts/bisect-hybrid-2k.mjs\` (data: [\`bisect-hybrid-2k.json\`](bisect-hybrid-2k.json)); re-checked by
[\`tests/local-bisect-hybrid-2k.test.ts\`](../tests/local-bisect-hybrid-2k.test.ts), which fails if the code no longer reproduces
every field below except the times.

- Measured ${report.measuredAt}${commit ? ` at commit \`${commit.slice(0, 12)}\`${dirty ? ' plus uncommitted changes' : ''}` : ''}, Node ${report.host.node}, ${report.host.platform}/${report.host.arch}${report.host.cpu ? `, ${report.host.cpu}` : ''}.
- Store: the demo's moment-3 ops corpus (seed ${report.seed}), ${report.records} records, one verified answer, one later false record at ordinary trust. Task: \`k = 1\`, depth 100.
- Retrieval: \`hybrid\` (dense + lexical, RRF \`rrfK\` ${cases[0].exactConfig?.rrfK}), embedder \`${cases[0].embedder.model}\` (${cases[0].embedder.dimensions} dimensions, ${cases[0].embedder.kind}), reranker off.

| Dense index | Records | Outcome | Blamed | Precision | Oracle B confirmed | Oracle B path | Passages re-embedded | Bisect s | Case s |
|---|---|---|---|---|---|---|---|---|---|
${rows.join('\n')}

Precision is the share of the blame set that is the seeded record. "Case s" includes seeding and embedding the store.

**Limits.** ${report.limits}
`;
writeFileSync(join(outDir, 'bisect-hybrid-2k.md'), markdown);
for (const entry of cases) process.stdout.write(`${entry.indexRequested}: ${entry.outcome}, precision ${fixed(entry.precision, 2)}, ${entry.records} records, bisect ${fixed(entry.bisectSeconds, 2)} s\n`);
